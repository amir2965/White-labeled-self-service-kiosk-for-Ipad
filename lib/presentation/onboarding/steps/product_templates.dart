  static List<Map<String, dynamic>> getTemplatesByCategory(String category) {
    if (category == 'All') return commonTemplates;
    final names = categoryGroups[category];
    if (names != null && names.isNotEmpty) {
      return names
          .map((n) => getTemplateByName(n))
          .whereType<Map<String, dynamic>>()
          .toList();
    }
    return commonTemplates.where((t) => t['category'] == category).toList();
  }

  static Map<String, dynamic>? getTemplateByName(String name) {
    try {
      return commonTemplates.firstWhere((t) => t['name'] == name);
    } catch (e) {
      return null;
    }
  }
